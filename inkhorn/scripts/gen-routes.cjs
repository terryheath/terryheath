#!/usr/bin/env node
// gen-routes.cjs — writes inkhorn/routes.yaml and inkhorn/redirects.yaml for Inkhorn Press (theme 1.4.0).
// Usage: node scripts/gen-routes.cjs   (reads data/issues.json)
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const { issues } = JSON.parse(fs.readFileSync(path.join(root, 'data/issues.json'), 'utf8'));
const GENRES = ['poetry', 'fiction', 'nonfiction', 'art', 'micro'];

let r = `# Generated by scripts/gen-routes.cjs — edit data/issues.json, not this file.
routes:
  /:
    template: home
    data: page.home

  /submit/:
    template: submit
  /events/:
    template: events
  /weird-friday/:
    template: weird-friday
  /bookfolk/:
    template: bookfolk
  /support/:
    template: support

  /shop/:
    template: page-books
    data: page.books
  /shop/print-edition/:
    template: page
    data: page.print-edition
  /shop/cart/:
    template: page-cart
    data: page.cart
  /shop/order-complete/:
    template: page-order-complete
    data: page.order-complete
  /shop/address/:
    template: page-address
    data: page.address

  /white-rabbit/no-1/:
    template: white-rabbit-issue

  /review/issues/:
    template: review-issues
  /review/founder-letter/:
    controller: channel
    template: tag-letter
    filter: tag:letter
    data: tag.letter
    order: published_at desc
`;
for (const i of issues) r += `  /review/${i}/:\n    template: edition\n    data: tag.${i}\n`;
r += '\n';
for (const g of GENRES) r += `  /${g}/:\n    controller: channel\n    template: tag-${g}\n    filter: tag:${g}\n    data: tag.${g}\n    order: published_at desc\n    limit: 999\n`;
r += `
collections:
  /digest/:
    permalink: /digest/{slug}/
    template: index
    filter: tag:hash-digest
    order: published_at desc
    limit: 999

  /life-on-words/:
    permalink: /life-on-words/{slug}/
    template: tag-podcast
    filter: primary_tag:podcast
    data: tag.podcast
    order: published_at desc
    limit: 999

  /white-rabbit/:
    permalink: /white-rabbit/{slug}/
    template: white-rabbit
    filter: tag:white-rabbit
    order: published_at desc
    limit: 999

  /review/:
    permalink: /review/{slug}/
    template: review
    filter: tag:-[hash-weekly-email,hash-digest,podcast]
    order: published_at desc
    limit: 12

taxonomies:
  tag: /by/{slug}/
  author: /author/{slug}/
`;
fs.writeFileSync(path.join(root, 'routes.yaml'), r);

// ---- redirects (first match wins; specific rules first; query strings are kept by Ghost) ----
const iss = issues.join('|');
const seasons = 'autumn|winter|spring|summer';
const red = [
  // existing rules, retargeted
  ['/print/', '/shop/'],
  ['^/september-2026/?$', '/review/autumn-2026/'],
  ['^/september-2026/([^/]+)/?$', '/review/$1/'],
  ['/tag/podcast/', 'https://terryheath.com/podcast/'],
  ['^/podcast/(.*)$', 'https://terryheath.com/podcast/$1'],
  ['/life-on-words/', 'https://terryheath.com/podcast/'],
  ['^/life-on-words/(.*)$', 'https://terryheath.com/podcast/$1'],
  ['/tag/letter/', '/review/founder-letter/'],
  ['/colophon/', '/review/founder-letter/'],
  ['/micro/tolls/', '/review/tolls/'],
  ['/micro/fledgling/', '/review/fledgling/'],
  ['/micro/lungs-of-truth/', '/review/lungs-of-truth/'],
  // tag pages that are not contributors
  [`^/tag/(${iss})/?$`, '/review/$1/'],
  ['^/tag/(poetry|fiction|nonfiction|art|micro)/?$', '/$1/'],
  // issue pages and their genre sub-pages
  [`^/(${iss})/(poetry|fiction|nonfiction)/?$`, '/review/$1/'],
  [`^/(${iss})/all/?$`, '/review/$1/'],
  [`^/(${iss})/?$`, '/review/$1/'],
  [`^/(${seasons})-20[0-9][0-9]/?$`, '/review/'],
  [`^/(${seasons})-20[0-9][0-9]/(poetry|fiction|nonfiction)/?$`, '/review/'],
  // pieces: /<issue>/<piece>/ and /<genre>/<piece>/
  [`^/(${seasons})-20[0-9][0-9]/([^/]+)/?$`, '/review/$2/'],
  ['^/(poetry|fiction|nonfiction|art|micro)/([^/]+)/?$', '/review/$2/'],
  ['^/founder-letter/?$', '/review/founder-letter/'],
  ['^/founder-letter/([^/]+)/?$', '/review/$1/'],
  ['^/archive/?$', '/review/'],
  ['^/rss/?$', '/review/rss/'],
  // shop
  ['^/books/?$', '/shop/'],
  ['^/print-edition/?$', '/shop/print-edition/'],
  ['^/cart/?$', '/shop/cart/'],
  ['^/order-complete/?$', '/shop/order-complete/'],
  ['^/address/?$', '/shop/address/'],
  // other pages
  ['^/submissions/?$', '/submit/'],
  ['^/patreon-supporters/?$', '/support/'],
  ['^/submit/review/?$', 'https://duotrope.com/duosuma/submit/inkhorn-review-iGX4p'],
  ['^/submit/white-rabbit/?$', '/white-rabbit/'],
  ['^/submit/muse/?$', 'https://gomuse.io'],
  ['^/muse/?$', 'https://gomuse.io'],
  ['^/author/[^/]+/?$', '/review/'],
  // contributors: every other tag
  ['^/tag/([^/]+)/?$', '/by/$1/'],
];
const q = s => `'${s.replace(/'/g, "''")}'`;
fs.writeFileSync(path.join(root, 'redirects.yaml'), '# Generated by scripts/gen-routes.cjs\n301:\n' + red.map(([a, b]) => `  ${q(a)}: ${q(b)}`).join('\n') + '\n');
console.log('routes.yaml, redirects.yaml written;', issues.length, 'issues,', red.length, 'redirects');
